-- =============================================================
-- CSE202 Banking System - database schema (H2)
-- Maps the class diagram to tables:
--   Customer          -> customers
--   Employer          -> employers      (0..1 per customer)
--   Account hierarchy -> accounts       (single table, account_type discriminator)
--   Transaction       -> transactions
--   Administrator     -> administrators
-- =============================================================

CREATE TABLE IF NOT EXISTS customers (
    customer_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(50)  NOT NULL,
    surname        VARCHAR(50)  NOT NULL,
    national_id    VARCHAR(20)  NOT NULL UNIQUE,
    address        VARCHAR(200) NOT NULL,
    phone          VARCHAR(20),
    email          VARCHAR(100),
    username       VARCHAR(50)  NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    salt           VARCHAR(50)  NOT NULL,
    created_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS employers (
    employer_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT       NOT NULL UNIQUE,
    company_name    VARCHAR(100) NOT NULL,
    company_address VARCHAR(200) NOT NULL,
    job_title       VARCHAR(100),
    CONSTRAINT fk_employer_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS accounts (
    account_number VARCHAR(20)   NOT NULL PRIMARY KEY,
    customer_id    BIGINT        NOT NULL,
    account_type   VARCHAR(20)   NOT NULL,
    branch         VARCHAR(100)  NOT NULL,
    balance        DECIMAL(15,2) NOT NULL DEFAULT 0,
    date_opened    DATE          NOT NULL,
    CONSTRAINT fk_account_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id) ON DELETE CASCADE,
    CONSTRAINT chk_account_type CHECK (account_type IN ('SAVINGS', 'INVESTMENT', 'CHEQUE')),
    CONSTRAINT chk_balance CHECK (balance >= 0)
);

CREATE TABLE IF NOT EXISTS transactions (
    transaction_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number   VARCHAR(20)   NOT NULL,
    transaction_type VARCHAR(20)   NOT NULL,
    amount           DECIMAL(15,2) NOT NULL,
    balance_after    DECIMAL(15,2) NOT NULL,
    transaction_time TIMESTAMP     NOT NULL,
    reference        VARCHAR(100),
    CONSTRAINT fk_transaction_account FOREIGN KEY (account_number)
        REFERENCES accounts (account_number) ON DELETE CASCADE,
    CONSTRAINT chk_transaction_type CHECK (transaction_type IN ('OPENING_DEPOSIT', 'DEPOSIT', 'WITHDRAWAL', 'INTEREST')),
    CONSTRAINT chk_amount CHECK (amount > 0)
);

CREATE TABLE IF NOT EXISTS administrators (
    admin_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    full_name     VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    salt          VARCHAR(50)  NOT NULL
);

CREATE SEQUENCE IF NOT EXISTS account_number_seq START WITH 1000001;

CREATE INDEX IF NOT EXISTS idx_accounts_customer ON accounts (customer_id);
CREATE INDEX IF NOT EXISTS idx_transactions_account ON transactions (account_number);
